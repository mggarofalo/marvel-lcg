    [Fact]
    [Rule("rr:initiating-abilities.step.5")]
    [Rule("rr:initiating-abilities.step.6")]
    public void SpentCopyRespondsBeforePaidCardEnters()
    {
        // Step 5 pays costs; step 6 commences the card being played.
        var runner = Runner();
        var world = ThorActualFixture.Board("06001a");
        world.Abilities = runner;
        var seat = world.Seats[0];
        var played = world.CreateCard("21019", seat.Hand);
        var spent = world.CreateCard("12006", seat.Hand);
        var other = world.CreateCard("12006", seat.Hand);
        CardPlay.Play(world, world.Facts, runner, seat, played, [spent.ObjectId], []);
        var prompt = Assert.IsType<Prompt>(Sequence.Work(world, world.Facts, runner, []));
        Assert.NotEqual(DeckType.AlliesArea, played.Area.Type);
        var response = Assert.Single(prompt.Affordances, item => item.AnchorId == spent.ObjectId);
        Assert.DoesNotContain(prompt.Affordances, item => item.AnchorId == other.ObjectId);
        Sequence.Answer(world, world.Facts, runner, prompt, Decision.Take(response.Id), []);
        Sequence.Finish(world, world.Facts, runner, []);
        Assert.Equal(1, seat.IdentityCard.Tokens.GetValueOrDefault("c_spent_seen"));
        Assert.Equal(DeckType.AlliesArea, played.Area.Type);
        Assert.Equal(DeckType.DiscardPile, spent.Area.Type);
        Assert.Same(seat.Hand, other.Area);
    }

    [Theory]
    [InlineData("12001b", false, 3, 0)]
    [InlineData("12001a", true, 3, 1)]
    [InlineData("12001c", true, 1, 0)]
    [Rule("rr:cost.4")]
    public void WhollyExcessStillOffersOnlyInHeroForm(string form, bool offered, int damage, int draws)
    {
        // Excess resources "were not paid" but the physical card was spent.
        var runner = Runner(pymEffect: true);
        var world = ThorActualFixture.Board("06001a");
        world.Abilities = runner;
        var seat = world.Seats[0];
        World.MoveToTop(seat.IdentityCard, world.AreaOf(DeckType.RemovedArea));
        seat.IdentityCard = world.CreateCard("12001a,12001b,12001c", seat.Hero);
        seat.IdentityCard.TurnTo(form);
        seat.IdentityCard.TakeDamage(3);
        var played = world.CreateCard("01069", seat.Hand);
        var spent = world.CreateCard("12006", seat.Hand);
        for (int n = 0; n < 3; n++) world.CreateCard("01087", seat.Deck);
        int held = seat.Hand.Cards.Count;
        Assert.Equal(0, CardPayment.CostOf(world, world.Facts, seat, played).Amount);
        CardPlay.Play(world, world.Facts, runner, seat, played, [spent.ObjectId], []);
        var prompt = Sequence.Work(world, world.Facts, runner, []);
        if (offered)
        {
            var response = Assert.Single(prompt!.Affordances, item => item.AnchorId == spent.ObjectId);
            Sequence.Answer(world, world.Facts, runner, prompt, Decision.Take(response.Id), []);
            Sequence.Finish(world, world.Facts, runner, []);
        }
        else Assert.Null(prompt);
        Assert.Equal(damage, seat.IdentityCard.Damage);
        Assert.Equal(held - 2 + draws, seat.Hand.Cards.Count);
        Assert.Equal(DeckType.DiscardPile, played.Area.Type);
    }

    [Fact]
    [Rule("rr:resource.1")]
    public void OrdinaryDiscardDoesNotCreateSpendResponse()
    {
        // Resources are generated by discarding cards to pay a cost.
        var runner = Runner();
        var world = ThorActualFixture.Board("06001a");
        world.Abilities = runner;
        var card = world.CreateCard("12006", world.Seats[0].Hand);
        Discard.Card(world, card, "test", []);
        Assert.Empty(runner.Waiting(world, new Occurrence(123, ["Discard"], card.ObjectId, 0), WindowKind.Response));
        var paid = world.CreateCard("21019", world.Seats[0].Hand);
        var control = world.CreateCard("12006", world.Seats[0].Hand);
        CardPlay.Play(world, world.Facts, runner, world.Seats[0], paid, [control.ObjectId], []);
        var prompt = Assert.IsType<Prompt>(Sequence.Work(world, world.Facts, runner, []));
        Assert.Contains(prompt.Affordances, item => item.AnchorId == control.ObjectId);
        Assert.DoesNotContain(prompt.Affordances, item => item.AnchorId == card.ObjectId);
        Sequence.Answer(world, world.Facts, runner, prompt, Decision.Decline, []);
        Sequence.Finish(world, world.Facts, runner, []);
        Assert.Equal(0, world.Seats[0].IdentityCard.Tokens.GetValueOrDefault("c_spent_seen"));
        Assert.Equal(DeckType.AlliesArea, paid.Area.Type);
        Assert.False(world.Agenda.IsBusy);
    }

    [Fact]
    [Rule("rr:cost.5")]
    public void SuspendedGeneratorAndLaterExhaustCostFinishBeforeResponse()
    {
        // Multiple costs "must be paid simultaneously" before the effect.
        var runner = Runner(withAction: true);
        Card? source = null;
        Card? generator = null;
        Card? spent = null;
        var (game, world) = Playing(board =>
        {
            source = InPlay(board, "01006");
            generator = board.CreateCard("01030", board.AreaOf(DeckType.AlliesArea, PlayArea.Of(0), cardOwner: 0));
            generator.TakeDamage(2);
            InPlay(board, "01092");
            spent = board.CreateCard("12006", board.Seats[0].Hand);
        }, hero: true, abilities: runner);
        var action = Assert.Single(game.Pending!.Affordances, item => item.AnchorId == source!.ObjectId);
        int[] paying = [spent!.ObjectId, generator!.ObjectId];
        var allocations = ResourcePayment.Allocate(Assert.Single(action.Costs!), paying)!;
        game.Resolve(new Decision(action.Id, [], paying, Allocations: allocations));
        Assert.Equal(Question.Opportunity, game.Pending!.Asking);
        Assert.True(source!.Ready);
        Assert.Equal(0, source.Tokens.GetValueOrDefault("c_test"));
        game.Resolve(Decision.Decline);
        Assert.False(source.Ready);
        Assert.Equal(0, source.Tokens.GetValueOrDefault("c_test"));
        var response = Assert.Single(game.Pending!.Affordances, item => item.AnchorId == spent.ObjectId);
        game.Resolve(Decision.Take(response.Id));
        Assert.Equal(1, source.Tokens.GetValueOrDefault("c_test"));
        Assert.Equal(1, world.Seats[0].IdentityCard.Tokens.GetValueOrDefault("c_spent_seen"));
        Assert.Equal(DeckType.DiscardPile, generator.Area.Type);
        Assert.False(world.Agenda.IsBusy);
    }

    [Fact]
    [Rule("rr:triggering-condition.2")]
    public void TwoSpentCopiesShareOneResponseWindowAndEachCanBeUsedOnce()
    {
        // One occurrence has "a single ... response window".
        var runner = Runner();
        var world = ThorActualFixture.Board("06001a");
        world.Abilities = runner;
        var seat = world.Seats[0];
        var played = world.CreateCard("21019", seat.Hand);
        var first = world.CreateCard("12006", seat.Hand);
        var second = world.CreateCard("12006", seat.Hand);
        CardPlay.Play(world, world.Facts, runner, seat, played, [first.ObjectId, second.ObjectId], []);
        var prompt = Assert.IsType<Prompt>(Sequence.Work(world, world.Facts, runner, []));
        Assert.Contains(prompt.Affordances, item => item.AnchorId == first.ObjectId);
        Assert.Contains(prompt.Affordances, item => item.AnchorId == second.ObjectId);
        var chosen = prompt.Affordances.Single(item => item.AnchorId == second.ObjectId);
        Sequence.Answer(world, world.Facts, runner, prompt, Decision.Take(chosen.Id), []);
        prompt = Assert.IsType<Prompt>(Sequence.Work(world, world.Facts, runner, []));
        Assert.DoesNotContain(prompt.Affordances, item => item.AnchorId == second.ObjectId);
        chosen = Assert.Single(prompt.Affordances, item => item.AnchorId == first.ObjectId);
        Sequence.Answer(world, world.Facts, runner, prompt, Decision.Take(chosen.Id), []);
        Sequence.Finish(world, world.Facts, runner, []);
        Assert.Equal(2, seat.IdentityCard.Tokens.GetValueOrDefault("c_spent_seen"));
        Assert.Equal(DeckType.AlliesArea, played.Area.Type);
    }

    [Fact]
    public void EffectPaymentResponsePrecedesTheFollowingInstruction()
    {
        var runner = Runner(withChoice: true);
        Card? source = null;
        Card? spent = null;
        var (game, world) = Playing(board =>
        {
            source = InPlay(board, "01006");
            spent = board.CreateCard("12006", board.Seats[0].Hand);
        }, hero: true, abilities: runner);
        var action = Assert.Single(game.Pending!.Affordances, item => item.AnchorId == source!.ObjectId);
        game.Resolve(Decision.Take(action.Id));
        var pay = Assert.Single(game.Pending!.Affordances, item => item.CostOptions.Count > 0);
        int[] cards = [spent!.ObjectId];
        game.Resolve(new Decision(pay.Id, [], cards,
            Allocations: ResourcePayment.Allocate(Assert.Single(pay.Costs!), cards)));
        Assert.Equal(0, source!.Tokens.GetValueOrDefault("c_test"));
        var response = Assert.Single(game.Pending!.Affordances, item => item.AnchorId == spent.ObjectId);
        game.Resolve(Decision.Take(response.Id));
        Assert.Equal(1, source.Tokens.GetValueOrDefault("c_test"));
        Assert.Equal(1, world.Seats[0].IdentityCard.Tokens.GetValueOrDefault("c_spent_seen"));
        Assert.False(world.Agenda.IsBusy);
    }

    [Fact]
    [Rule("rr:cost.5")]
    public void OtherPlayersContributingCopyRespondsForItsOwner()
    {
        // A player may generate resources for simultaneous Alliance costs.
        var runner = Runner();
        var world = ThorActualFixture.Board("06001a", 2);
        world.Abilities = runner;
        var played = world.CreateCard("21019", world.Seats[0].Hand);
        world.Effects.Register(new ContinuousEffect(EffectSource.LastingEffect, "alliance", 1, Affects: played.ObjectId));
        var spent = world.CreateCard("12006", world.Seats[1].Hand);
        CardPlay.Play(world, world.Facts, runner, world.Seats[0], played, [spent.ObjectId], []);
        var prompt = Assert.IsType<Prompt>(Sequence.Work(world, world.Facts, runner, []));
        Assert.Equal(1, prompt.Player);
        var response = Assert.Single(prompt.Affordances, item => item.AnchorId == spent.ObjectId);
        Sequence.Answer(world, world.Facts, runner, prompt, Decision.Take(response.Id), []);
        Sequence.Finish(world, world.Facts, runner, []);
        Assert.Equal(0, world.Seats[0].IdentityCard.Tokens.GetValueOrDefault("c_spent_seen"));
        Assert.Equal(1, world.Seats[1].IdentityCard.Tokens.GetValueOrDefault("c_spent_seen"));
        Assert.Equal(DeckType.AlliesArea, played.Area.Type);
    }

    [Fact]
    public void SuspendedEffectPaymentResumesAfterItsSpendResponse()
    {
        var runner = Runner(withAction: true, withChoice: true);
        Card? source = null;
        Card? generator = null;
        Card? spent = null;
        var (game, world) = Playing(board =>
        {
            source = InPlay(board, "01006");
            generator = board.CreateCard("01030", board.AreaOf(DeckType.AlliesArea, PlayArea.Of(0), cardOwner: 0));
            generator.TakeDamage(2);
            InPlay(board, "01092");
            spent = board.CreateCard("12006", board.Seats[0].Hand);
        }, hero: true, abilities: runner);
        var action = Assert.Single(game.Pending!.Affordances, item => item.AnchorId == source!.ObjectId);
        game.Resolve(Decision.Take(action.Id));
        var pay = Assert.Single(game.Pending!.Affordances, item => item.CostOptions.Count > 0);
        int[] cards = [spent!.ObjectId, generator!.ObjectId];
        game.Resolve(new Decision(pay.Id, [], cards, Allocations: ResourcePayment.Allocate(Assert.Single(pay.Costs!), cards)));
        Assert.Equal(0, source!.Tokens.GetValueOrDefault("c_test"));
        game.Resolve(Decision.Decline);
        Assert.Equal(0, source.Tokens.GetValueOrDefault("c_test"));
        var response = Assert.Single(game.Pending!.Affordances, item => item.AnchorId == spent.ObjectId);
        game.Resolve(Decision.Take(response.Id));
        Assert.Equal(1, source.Tokens.GetValueOrDefault("c_test"));
        Assert.Equal(1, world.Seats[0].IdentityCard.Tokens.GetValueOrDefault("c_spent_seen"));
        Assert.Equal(DeckType.DiscardPile, generator.Area.Type);
        Assert.False(world.Agenda.IsBusy);
    }

    internal static AbilityRunner Runner(bool withAction = false, bool pymEffect = false, bool withChoice = false)
    {
        var root = JsonNode.Parse(AuthoredCards.Text)!;
        root["cards"]!.AsArray().Add(JsonNode.Parse("""
            {"card":"12006","abilities":[{
              "trigger":{"event":"WhenResourceCardSpent","timing":"Response","subject":"this","player":"you","form":"hero"},
              "effect":{"placeCounters":{"card":"you","counter":"spent_seen","count":1}}
            }]}
            """));
        if (pymEffect)
            root["cards"]!.AsArray().Last()!["abilities"]![0]!["effect"] = JsonNode.Parse("""
              {"if":{"test":{"hasTrait":{"card":"you","trait":"GIANT"}},
                "then":{"heal":{"card":"yourHero","amount":2}},
                "else":{"if":{"test":{"hasTrait":{"card":"you","trait":"TINY"}},
                  "then":{"draw":{"player":"you","count":1}}}}}}
              """);
        if (withAction)
        {
            var rows = root["cards"]!.AsArray();
            foreach (string id in new[] { "01006", "01030", "01092" })
                rows.Remove(rows.Single(row => row!["card"]!.GetValue<string>() == id));
            foreach (var row in JsonNode.Parse("""
              [{"card":"01006","abilities":[{
                "trigger":{"event":"WhenActionTriggered","timing":"Action","subject":"game"},
                "cost":{"seq":[{"spend":"YY"},{"exhaust":"this"}]},
                "effect":{"placeCounters":{"card":"this","counter":"test","count":1}}}]},
               {"card":"01030","abilities":[{
                "trigger":{"event":"WhenActionTriggered","timing":"Resource","subject":"game"},
                "cost":{"dealDamage":{"cards":"this","amount":2}},"effect":{"generate":"Y"}}]},
               {"card":"01092","abilities":[{
                "trigger":{"event":"WhenCardWouldBeDefeated","timing":"Interrupt","subject":"game"},
                "effect":{"draw":{"player":"you","count":1}}}]}]
              """)!.AsArray()) rows.Add(row!.DeepClone());
        }
        if (withChoice)
        {
            var rows = root["cards"]!.AsArray();
            rows.Remove(rows.Single(row => row!["card"]!.GetValue<string>() == "01006"));
            rows.Add(JsonNode.Parse("""
              {"card":"01006","abilities":[{
                "trigger":{"event":"WhenActionTriggered","timing":"Action","subject":"game"},
                "effect":{"seq":[{"payOrExhaust":{"resources":"Y","otherwise":{"exhaust":"this"}}},
                  {"placeCounters":{"card":"this","counter":"test","count":1}}]}}]}
              """));
        }
        return new AbilityRunner(AbilityCatalog.Parse(root.ToJsonString()));
    }
