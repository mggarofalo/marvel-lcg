namespace Marvel.Content.Setup;

/// <summary>The authored product role of a named encounter set.</summary>
public enum EncounterSetRole
{
    /// <summary>A selectable modular set.</summary>
    Modular,
    /// <summary>The fixed Standard set.</summary>
    Standard,
    /// <summary>The fixed Expert set.</summary>
    Expert,
    /// <summary>Cards belonging to one scenario.</summary>
    Scenario,
    /// <summary>Cards associated with an identity's nemesis.</summary>
    Nemesis,
}
