using Marvel.Cards.Dsl;

namespace Marvel.Cards.Run;

// These are engine-owned operation spellings for existing option labels,
// diagnostics and continuation paths. They are derived from checked instructions,
// never used to recover operands from authored argument maps.
internal static class AbilityOperationNames
{
    internal static string OperationName(this AbilityCost cost) => cost switch
    {
        AbilityCost.Sequence => "seq",
        AbilityCost.Exhaust => "exhaust",
        AbilityCost.ExhaustTitled => "exhaustTitled",
        AbilityCost.Discard => "discard",
        AbilityCost.ReturnSourceToHand => "returnToHand",
        AbilityCost.ReturnTitledToHand => "returnTitledToHand",
        AbilityCost.DiscardTop => "discardTop",
        AbilityCost.DealEncounterToYou => "dealEncounterCard",
        AbilityCost.ConsumeCampaignCard => "consumeCampaignCard",
        AbilityCost.RemoveCounters => "removeCounters",
        AbilityCost.Spend { DistinctTypes: true } => "spendDistinct",
        AbilityCost.Spend { Generic: > 0 } => "spendAny",
        AbilityCost.Spend spend => spend.PrintedOnly ? "spendPrinted" : "spend",
        AbilityCost.SpendEnergy => "spendEnergyX",
        AbilityCost.RandomDiscardFromHand => "discardRandomFromHand",
        AbilityCost.DiscardFromHand discard => discard.Range switch
        {
            AbilityCostRange.Exact => "discardFromHand",
            AbilityCostRange.UpTo => "discardUpToFromHand",
            AbilityCostRange.Any => "discardAnyFromHand",
            _ => throw new InvalidOperationException("Unknown discard cost range"),
        },
        AbilityCost.ExhaustChosen => "exhaustChosen",
        AbilityCost.Heal => "heal",
        AbilityCost.Damage damage => damage.MustTakeAll ? "takeDamage" : "dealDamage",
        _ => throw new InvalidOperationException("Unknown compiled cost"),
    };

    internal static string OperationName(this AbilityEffect effect) => effect switch
    {
        AbilityEffect.AttackAnotherEnemy => "attackAnotherEnemy",
        AbilityEffect.ModifyPlayedEvent => "modifyPlayedEvent",
        AbilityEffect.Heal => "heal",
        AbilityEffect.SetHitPoints => "setHitPoints",
        AbilityEffect.Damage => "dealDamage",
        AbilityEffect.AttackDamage => "dealAttackDamage",
        AbilityEffect.IndirectDamage => "indirectDamage",
        AbilityEffect.GiveStatus => "giveStatus",
        AbilityEffect.RemoveStatuses => "removeStatuses",
        AbilityEffect.ChangeForm => "changeForm",
        AbilityEffect.Draw => "draw",
        AbilityEffect.PlaceThreat => "placeThreat",
        AbilityEffect.RemoveThreat => "removeThreat",
        AbilityEffect.PreventThreat => "preventThreat",
        AbilityEffect.PreventDamage => "preventDamage",
        AbilityEffect.GainSurge => "gainSurge",
        AbilityEffect.Generate => "generate",
        AbilityEffect.DoubleResourceFor => "doubleResourceFor",
        AbilityEffect.ReduceFirstAllyCost => "reduceFirstAllyCost",
        AbilityEffect.AllowPlayBeneath => "allowPlayBeneath",
        AbilityEffect.AllowPlayFromDiscard => "allowPlayFromDiscard",
        AbilityEffect.AttachCards => "attachCards",
        AbilityEffect.ReleaseBeneath => "releaseBeneath",
        AbilityEffect.ChooseCardsToHand => "chooseCardsToHand",
        AbilityEffect.StoreBeneath => "storeBeneath",
        AbilityEffect.InitializeAuxiliaryDeck => "initializeAuxiliaryDeck",
        AbilityEffect.RevealAuxiliaryTop => "revealAuxiliaryTop",
        AbilityEffect.Shuffle => "shuffle",
        AbilityEffect.GrantTraitCharacters => "grantCharactersWithTrait",
        AbilityEffect.GrantControlledCharacters => "grantCharactersControlledBy",
        AbilityEffect.PreventDamageFrom => "preventDamageFrom",
        AbilityEffect.PreventDamageWhile => "preventDamageWhile",
        AbilityEffect.DelayedDiscard => "delayUntil",
        AbilityEffect.DelayedStun => "delayUntil",
        AbilityEffect.DealEncounterCards => "dealEncounterCards",
        AbilityEffect.EngageTopAsMinion => "engageTopAsMinion",
        AbilityEffect.DefineProfile => "defineProfile",
        AbilityEffect.DefineBaseValue => "defineBaseValue",
        AbilityEffect.DealEncounterCard => "dealEncounterCard",
        AbilityEffect.DiscardAtRandom => "discardAtRandom",
        AbilityEffect.PlaceAtRandom => "placeAtRandom",
        AbilityEffect.DiscardTop => "discardTop",
        AbilityEffect.DiscardUntil => "discardUntil",
        AbilityEffect.ShuffleInto => "shuffleInto",
        AbilityEffect.Search => "search",
        AbilityEffect.RecruitDiscarded => "recruitDiscarded",
        AbilityEffect.PutIntoPlay => "putIntoPlay",
        AbilityEffect.InspectEncounterTop => "inspectEncounterTop",
        AbilityEffect.ChooseTopForHand => "chooseTopForHand",
        AbilityEffect.DiscardHandCards => "discardHandCards",
        AbilityEffect.DiscardResourceIcons => "discardResourceIcons",
        AbilityEffect.ChooseDiscardToShuffle => "chooseDiscardToShuffle",
        AbilityEffect.PlaceCounters => "placeCounters",
        AbilityEffect.RemoveCounters => "removeCounters",
        AbilityEffect.DiscardHandWithResource => "discardHandWithResource",
        AbilityEffect.RecoverDiscardedByResource => "recoverDiscardedByResource",
        AbilityEffect.ReduceNextCardCost => "reduceNextCardCost",
        AbilityEffect.Sequence => "seq",
        AbilityEffect.Simultaneous => "and",
        AbilityEffect.Conditional => "if",
        AbilityEffect.EachPlayer => "eachPlayer",
        AbilityEffect.ForEach => "forEach",
        AbilityEffect.EachTime => "eachTime",
        AbilityEffect.Choose => "choose",
        AbilityEffect.ChooseCard => "chooseCard",
        AbilityEffect.AfterActivation => "afterActivation",
        AbilityEffect.Dependent dependent => dependent.OnFull ? "then" : "otherwise",
        AbilityEffect.MoveThreat => "moveThreat",
        AbilityEffect.MoveDamage move => move.Attack ? "moveAttackDamage" : "moveDamage",
        AbilityEffect.DrawToHandSize draw => draw.Printed ? "drawToPrintedHandSize" : "drawToHandSize",
        AbilityEffect.PayOrEffect payment => payment.ExhaustOnly ? "payOrExhaust" : "payOrEffect",
        AbilityEffect.GrantTrait grant => grant.Until is not null ? "grantUntil" : grant.EachCard ? "grantEach" : "grant",
        AbilityEffect.GrantField grant => grant.Until is not null ? "grantUntil" : grant.EachCard ? "grantEach" : "grant",
        AbilityEffect.ActivateEnemies activation => activation.Attack ? "enemyAttacks" : "enemySchemes",
        AbilityEffect.Power power => power.Kind switch
        {
            AbilityPowerKind.Attack => "attack",
            AbilityPowerKind.Thwart => "thwart",
            AbilityPowerKind.Defense => "defense",
            _ => throw new InvalidOperationException("Unknown power kind"),
        },
        AbilityEffect.ThwartGroup group => group.Selection switch
        {
            AbilityThwartSelection.All => "thwartSchemes",
            AbilityThwartSelection.Distributed => "distributeThreat",
            AbilityThwartSelection.Different => "thwartDifferentSchemes",
            AbilityThwartSelection.LegalPractice => "legalPractice",
            _ => throw new InvalidOperationException("Unknown thwart selection"),
        },
        AbilityEffect.CardAction action => action.Instruction switch
        {
            AbilityCardInstruction.Exhaust => "exhaust",
            AbilityCardInstruction.Ready => "ready",
            AbilityCardInstruction.MoveActiveCounter => "moveActiveCounter",
            AbilityCardInstruction.Discard => "discard",
            AbilityCardInstruction.RemoveFromGame => "removeFromGame",
            AbilityCardInstruction.ReturnToHand => "returnToHand",
            AbilityCardInstruction.ReturnOwnedToDiscard => "returnOwnedToDiscard",
            AbilityCardInstruction.ReturnOwnedToHand => "returnOwnedToHand",
            AbilityCardInstruction.AddToHand => "addToHand",
            AbilityCardInstruction.PlaceOnBottomOfDeck => "placeOnBottomOfDeck",
            AbilityCardInstruction.Reveal => "reveal",
            AbilityCardInstruction.RevealFromVillainDeck => "revealFromVillainDeck",
            AbilityCardInstruction.AttachTo => "attachTo",
            AbilityCardInstruction.GiveAdditionalBoost => "giveAdditionalBoost",
            AbilityCardInstruction.SoakDamage => "soakDamage",
            AbilityCardInstruction.ReplaceThreatWithDamage => "replaceThreatWithDamage",
            AbilityCardInstruction.ResolveSpecials => "resolveSpecials",
            AbilityCardInstruction.PreventThreatRemoval => "preventThreatRemoval",
            AbilityCardInstruction.PreventThwarting => "preventThwarting",
            AbilityCardInstruction.PreventReady => "preventReady",
            AbilityCardInstruction.DeclareDefender => "declareDefender",
            _ => throw new InvalidOperationException("Unknown card instruction"),
        },
        AbilityEffect.Fixed instruction => instruction.Instruction switch
        {
            AbilityFixedInstruction.UseAttackForThwart => "useAttackForThwart",
            AbilityFixedInstruction.AdvanceMainScheme => "advanceMainScheme",
            AbilityFixedInstruction.CancelOccurrence => "cancelOccurrence",
            AbilityFixedInstruction.CancelWhenRevealed => "cancelWhenRevealed",
            AbilityFixedInstruction.AlsoAttackEachOtherHero => "alsoAttackEachOtherHero",
            AbilityFixedInstruction.MakeAttackIndirect => "makeAttackIndirect",
            AbilityFixedInstruction.ReflectAttackDamage => "reflectAttackDamage",
            AbilityFixedInstruction.PreventAttackDamage => "preventAttackDamage",
            AbilityFixedInstruction.RevealTop => "revealTop",
            AbilityFixedInstruction.PeekAnyDeck => "peekTop",
            AbilityFixedInstruction.PlaceAccelerationToken => "placeAccelerationToken",
            AbilityFixedInstruction.GenerateTopDiscard => "generateTopDiscard",
            AbilityFixedInstruction.MakeTheCall => "makeTheCall",
            AbilityFixedInstruction.DiscardOtherEnvironments => "discardOtherEnvironments",
            AbilityFixedInstruction.GainEnvironmentTraits => "gainEnvironmentTraits",
            AbilityFixedInstruction.PreventSideSchemeDeparture => "preventSideSchemeDeparture",
            AbilityFixedInstruction.RequireAllyDefender => "requireAllyDefender",
            AbilityFixedInstruction.RequireAttackedPlayerAllyDefender => "requireAttackedPlayerAllyDefender",
            _ => throw new InvalidOperationException("Unknown fixed instruction"),
        },
        _ => throw new InvalidOperationException("Unknown compiled effect"),
    };
}
